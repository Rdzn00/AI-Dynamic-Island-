    fun t(k: String, vararg a: String): String {
        val m = when (lang.value) {
            "en" -> en
            "zh" -> zh
            else -> ms
        }
        var s = m[k] ?: ms[k] ?: k
        for (i in a.indices) {
            s = s.replace("{" + i + "}", a[i])
        }
        return s
    }

